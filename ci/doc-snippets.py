#!/usr/bin/env python3
"""Checks that the code in the README and docs/ works against the published PassKi artifacts.

1. Every `com.alirezaiyan.passki` coordinate and plugin version shown names a published artifact and the current
   VERSION_NAME.
2. Every Kotlin example compiles (ci/doc-snippets, Kotlin 2.2.21): each becomes a function, or stays top-level when it
   declares a type or a function. Placeholders the examples take for granted (`api`, `scope`, `log`, ...) live in
   ci/doc-snippets/src/jvmMain/kotlin/Prelude.kt.
3. Every `passki { }` block configures in a real Android app build.

PassKi must be in Maven Local first:
  ./gradlew publishToMavenLocal && ./gradlew -p passki-gradle-plugin publishToMavenLocal

Usage: python3 ci/doc-snippets.py   (from the repository root)
"""
import glob
import os
import re
import shutil
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PROJECT = os.path.join(ROOT, "ci", "doc-snippets")
GENERATED = os.path.join(PROJECT, "build", "generated", "snippets")
DSL_PROJECTS = os.path.join(PROJECT, "build", "dsl")
DOCS = ["README.md"] + sorted(os.path.relpath(p, ROOT) for p in glob.glob(os.path.join(ROOT, "docs", "*.md")))
GRADLEW = os.path.join(ROOT, "gradlew")

IMPORTS = """import androidx.compose.material3.*
import androidx.compose.runtime.*
import com.alirezaiyan.passki.*
import com.alirezaiyan.passki.compose.*
import com.alirezaiyan.passki.demo.*
import com.alirezaiyan.passki.test.*
import kotlinx.coroutines.*
"""


def version_name():
    with open(os.path.join(ROOT, "gradle.properties"), encoding="utf-8") as f:
        return re.search(r"^VERSION_NAME=(.+)$", f.read(), re.M).group(1).strip()


def published_artifacts():
    found = set()
    for path in glob.glob(os.path.join(ROOT, "*", "build.gradle.kts")):
        with open(path, encoding="utf-8") as f:
            found.update(re.findall(r'coordinates\(artifactId = "([^"]+)"\)', f.read()))
    return found


def code_blocks():
    """(file, line, language, body) for every fenced block in the README and docs/."""
    for name in DOCS:
        with open(os.path.join(ROOT, name), encoding="utf-8") as f:
            text = f.read()
        for m in re.finditer(r"^ *```(\w*)\n(.*?)^ *```", text, re.S | re.M):
            yield name, text[: m.start()].count("\n") + 1, m.group(1), m.group(2)


def is_gradle(body):
    return re.search(r"^\s*(plugins \{|passki \{|dependencies \{|\w+Main\.dependencies|\w+Test\.dependencies)", body, re.M) is not None


def dedent(body):
    lines = body.split("\n")
    indent = min((len(l) - len(l.lstrip()) for l in lines if l.strip()), default=0)
    return "\n".join(l[indent:] for l in lines)


def check_coordinates(blocks, version, artifacts):
    problems = []
    for name, line, _, body in blocks:
        for artifact, v in re.findall(r'"com\.alirezaiyan\.passki:([\w-]+):([^"]+)"', body):
            if artifact not in artifacts:
                problems.append(f"{name}:{line}: unknown artifact {artifact} (published: {', '.join(sorted(artifacts))})")
            if v != version:
                problems.append(f"{name}:{line}: {artifact}:{v}, but VERSION_NAME is {version}")
        for v in re.findall(r'id\("com\.alirezaiyan\.passki"\) version "([^"]+)"', body):
            if v != version:
                problems.append(f"{name}:{line}: plugin version {v}, but VERSION_NAME is {version}")
    return problems


def generate_kotlin(blocks):
    shutil.rmtree(GENERATED, ignore_errors=True)
    os.makedirs(GENERATED)
    count = 0
    for name, line, lang, body in blocks:
        if lang != "kotlin" or is_gradle(body):
            continue
        body = dedent(body)
        ident = re.sub(r"\W", "_", f"{name}_{line}")
        header = f"// {name}:{line}, generated by ci/doc-snippets.py.\n@file:Suppress(\"UNUSED_VARIABLE\", \"UNUSED_PARAMETER\", \"unused\")\n\npackage snippets\n\n{IMPORTS}\n"
        if re.search(r"^(@Composable|fun |suspend fun |interface |class |object |data class )", body, re.M):
            code = body
        elif re.search(r"\bremember\w*\(|\bButton\(|\bText\(", body):
            code = f"@Composable\nfun {ident}() {{\n{body}}}\n"
        else:
            code = f"suspend fun {ident}() {{\n{body}}}\n"
        with open(os.path.join(GENERATED, f"{ident}.kt"), "w", encoding="utf-8") as f:
            f.write(header + code)
        count += 1
    return count


def generate_dsl(blocks):
    """One Android app build per `passki { }` block; returns the project directories."""
    shutil.rmtree(DSL_PROJECTS, ignore_errors=True)
    projects = []
    for name, line, lang, body in blocks:
        m = re.search(r"^passki \{.*?^\}", dedent(body), re.S | re.M)
        if lang != "kotlin" or not m:
            continue
        ident = re.sub(r"\W", "_", f"{name}_{line}")
        directory = os.path.join(DSL_PROJECTS, ident)
        os.makedirs(directory)
        properties = os.path.join(ROOT, "gradle.properties")
        with open(os.path.join(directory, "settings.gradle.kts"), "w", encoding="utf-8") as f:
            f.write(
                "pluginManagement {\n    repositories { mavenLocal(); google(); mavenCentral(); gradlePluginPortal() }\n"
                f'    plugins {{ id("com.alirezaiyan.passki") version "{version_name()}" }}\n}}\n'
                "dependencyResolutionManagement { repositories { mavenLocal(); google(); mavenCentral() } }\n"
                f'rootProject.name = "{ident}"\n'
            )
        with open(os.path.join(directory, "build.gradle.kts"), "w", encoding="utf-8") as f:
            f.write(
                f"// The passki {{ }} block from {name}:{line}, generated by ci/doc-snippets.py.\n"
                'plugins {\n    id("com.android.application") version "9.1.1"\n    id("com.alirezaiyan.passki")\n}\n\n'
                'android {\n    namespace = "com.example.app"\n    compileSdk = 35\n'
                '    defaultConfig { applicationId = "com.example.app"; minSdk = 28 }\n}\n\n'
                + m.group(0) + "\n"
            )
        with open(os.path.join(directory, "gradle.properties"), "w", encoding="utf-8") as f:
            f.write("org.gradle.jvmargs=-Xmx2g\n")
        projects.append((f"{name}:{line}", directory))
    return projects


def gradle(*args):
    print("$ ./gradlew " + " ".join(args), flush=True)
    return subprocess.run([GRADLEW, *args, "--quiet"], cwd=ROOT).returncode == 0


def main():
    blocks = list(code_blocks())
    version = version_name()
    problems = check_coordinates(blocks, version, published_artifacts())
    for p in problems:
        print("coordinates: " + p)
    examples = generate_kotlin(blocks)
    projects = generate_dsl(blocks)
    print(f"{examples} Kotlin example(s), {len(projects)} passki {{ }} block(s), version {version}")
    ok = not problems
    ok = gradle("-p", os.path.relpath(PROJECT, ROOT), "compileKotlinJvm") and ok
    for label, directory in projects:
        if not gradle("-p", os.path.relpath(directory, ROOT), "help"):
            print(f"passki {{ }} block from {label} does not configure")
            ok = False
    print("doc snippets: OK" if ok else "doc snippets: FAILED")
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
