package com.alirezaiyan.passki.gradle.setup

import com.alirezaiyan.passki.gradle.Fingerprints
import groovy.json.JsonOutput

/**
 * What a WebAuthn server needs to accept this app's passkeys: the RP ID and every allowed origin
 * (`https://<rpId>` plus one `android:apk-key-hash:` per signing key). Written by `passkiSetup` to
 * `build/passki/server-config.json` (the same contract `passkiCheck` reads from `server.configUrl`),
 * with copy-paste snippets for popular verifiers.
 */
internal class ServerConfig(val rpId: String, val origins: List<String>, val appleAppIds: List<String>) {
    fun json(): String {
        val body = linkedMapOf("rpId" to rpId, "origins" to origins, "appleAppIds" to appleAppIds)
        return JsonOutput.prettyPrint(JsonOutput.toJson(body)) + "\n"
    }

    /** File name → snippet. */
    fun snippets(): Map<String, String> {
        val header = "Generated by ./gradlew passkiSetup for $rpId. Debug-key origins are included; drop them in production if you like."
        fun list(quote: String, indent: String) = origins.joinToString(",\n") { "$indent$quote$it$quote" }
        return linkedMapOf(
            "simplewebauthn.ts" to """
                |// $header
                |// npm i @simplewebauthn/server
                |import { verifyRegistrationResponse, verifyAuthenticationResponse } from "@simplewebauthn/server";
                |
                |export const rpID = "$rpId";
                |export const expectedOrigin = [
                |${list("\"", "  ")},
                |];
                |
                |// await verifyRegistrationResponse({ response, expectedChallenge, expectedOrigin, expectedRPID: rpID });
                |// await verifyAuthenticationResponse({ response, expectedChallenge, expectedOrigin, expectedRPID: rpID, credential });
                |""".trimMargin(),
            "webauthn4j.kt" to """
                |// $header
                |// com.webauthn4j:webauthn4j-core (written against $WEBAUTHN4J_VERSION)
                |import com.webauthn4j.WebAuthnManager
                |import com.webauthn4j.data.AuthenticationData
                |import com.webauthn4j.data.RegistrationData
                |import com.webauthn4j.data.client.Origin
                |import com.webauthn4j.data.client.challenge.Challenge
                |import com.webauthn4j.server.ServerProperty
                |
                |val rpId = "$rpId"
                |val origins: Set<Origin> = setOf(
                |${origins.joinToString(",\n") { "    Origin.create(\"$it\")" }},
                |)
                |
                |fun serverProperty(challenge: Challenge): ServerProperty =
                |    ServerProperty.builder().origins(origins).rpId(rpId).challenge(challenge).build()
                |
                |// Malformed JSON such as {"id":"x"} makes webauthn4j throw NullPointerException, not only
                |// DataConversionException. Catch RuntimeException so a bad request gets a 400, not a 500.
                |fun parseRegistration(manager: WebAuthnManager, json: String): RegistrationData? =
                |    try { manager.parseRegistrationResponseJSON(json) } catch (e: RuntimeException) { null }
                |
                |fun parseAuthentication(manager: WebAuthnManager, json: String): AuthenticationData? =
                |    try { manager.parseAuthenticationResponseJSON(json) } catch (e: RuntimeException) { null }
                |""".trimMargin(),
            "java-webauthn-server.kt" to """
                |// $header
                |// com.yubico:webauthn-server-core
                |import com.yubico.webauthn.RelyingParty
                |import com.yubico.webauthn.data.RelyingPartyIdentity
                |
                |val rpIdentity: RelyingPartyIdentity = RelyingPartyIdentity.builder().id("$rpId").name("$rpId").build()
                |val allowedOrigins: Set<String> = setOf(
                |${list("\"", "    ")},
                |)
                |
                |fun relyingParty(credentials: com.yubico.webauthn.CredentialRepository): RelyingParty =
                |    RelyingParty.builder()
                |        .identity(rpIdentity)
                |        .credentialRepository(credentials)
                |        .origins(allowedOrigins)
                |        .build()
                |""".trimMargin(),
            "py_webauthn.py" to """
                |# $header
                |# pip install webauthn
                |from webauthn import verify_registration_response, verify_authentication_response
                |
                |RP_ID = "$rpId"
                |EXPECTED_ORIGINS = [
                |${list("\"", "    ")},
                |]
                |
                |# verify_registration_response(credential=..., expected_challenge=..., expected_rp_id=RP_ID, expected_origin=EXPECTED_ORIGINS)
                |# verify_authentication_response(credential=..., expected_challenge=..., expected_rp_id=RP_ID, expected_origin=EXPECTED_ORIGINS, ...)
                |""".trimMargin(),
        )
    }

    companion object {
        /** webauthn4j release the generated snippet compiles against without deprecation warnings. */
        const val WEBAUTHN4J_VERSION = "0.30.0.RELEASE"

        fun of(rpId: String, fingerprintsByPackage: Map<String, List<String>>, appleAppIds: List<String>): ServerConfig {
            val android = fingerprintsByPackage.values.flatten().distinct().sorted().map(Fingerprints::androidOrigin)
            return ServerConfig(rpId, listOf("https://$rpId") + android, appleAppIds.distinct().sorted())
        }
    }
}
