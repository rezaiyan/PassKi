package com.alirezaiyan.passki.gradle.check

import groovy.json.JsonOutput

/** `passkiCheck` results rendered for the console, as JSON (`check.json`) and as a static HTML page. */
internal class CheckReport(val rpId: String, val results: List<CheckResult>, private val catalog: Catalog) {
    private fun count(status: CheckStatus) = results.count { it.status == status }

    /** Results that fail the build: FAILs, plus WARNs when [warningsAsErrors]. */
    fun failing(warningsAsErrors: Boolean): List<CheckResult> =
        results.filter { it.status == CheckStatus.FAIL || (warningsAsErrors && it.status == CheckStatus.WARN) }

    val summary: String
        get() = "${count(CheckStatus.PASS)} passed, ${plural(count(CheckStatus.WARN), "warning")}, " +
            "${count(CheckStatus.FAIL)} failed, ${count(CheckStatus.SKIP)} skipped"

    fun console(): String = buildString {
        append("PassKi check for ").append(rpId).append(": ").append(summary)
        results.forEach { result ->
            append('\n').append(result.status.marker).append(' ').append(result.id).append("  ")
            append(catalog[result.id].title).append(" - ").append(result.message)
            if (result.status == CheckStatus.WARN || result.status == CheckStatus.FAIL) {
                result.fix?.lines()?.forEachIndexed { index, line ->
                    append('\n').append(INDENT).append(if (index == 0) "fix: " else "     ").append(line)
                }
                append('\n').append(INDENT).append("docs: ").append(catalog.docsUrl(result.id))
            }
        }
    }

    fun json(): String {
        val body = linkedMapOf(
            "tool" to "passkiCheck",
            "catalogVersion" to catalog.version,
            "rpId" to rpId,
            "summary" to linkedMapOf(
                "pass" to count(CheckStatus.PASS),
                "warn" to count(CheckStatus.WARN),
                "fail" to count(CheckStatus.FAIL),
                "skip" to count(CheckStatus.SKIP),
            ),
            "checks" to results.map { result ->
                val entry = catalog[result.id]
                linkedMapOf(
                    "id" to result.id,
                    "status" to result.status.name,
                    "title" to entry.title,
                    "platform" to entry.platform,
                    "severity" to entry.severity,
                    "message" to result.message,
                    "fix" to result.fix,
                    "docs" to catalog.docsUrl(result.id),
                )
            },
        )
        return JsonOutput.prettyPrint(JsonOutput.toJson(body)) + "\n"
    }

    fun html(): String = buildString {
        append("<!doctype html>\n<html lang=\"en\">\n<head>\n<meta charset=\"utf-8\">\n")
        append("<meta name=\"viewport\" content=\"width=device-width, initial-scale=1\">\n")
        append("<title>PassKi check: ").append(esc(rpId)).append("</title>\n<style>\n").append(CSS).append("</style>\n</head>\n<body>\n<main>\n")
        append("<h1>PassKi check for ").append(esc(rpId)).append("</h1>\n")
        append("<p class=\"summary\">").append(esc(summary)).append("</p>\n")
        append("<table>\n<thead><tr><th>Status</th><th>ID</th><th>Check</th><th>Result</th></tr></thead>\n<tbody>\n")
        results.forEach { result ->
            val entry = catalog[result.id]
            val css = result.status.name.lowercase()
            append("<tr class=\"").append(css).append("\"><td><span class=\"badge ").append(css).append("\">")
            append(result.status.name).append("</span></td>")
            append("<td><a href=\"").append(esc(catalog.docsUrl(result.id))).append("\">").append(result.id).append("</a></td>")
            append("<td>").append(esc(entry.title)).append("</td><td>").append(esc(result.message))
            if (result.status == CheckStatus.WARN || result.status == CheckStatus.FAIL) {
                result.fix?.let { append("<div class=\"fix\"><b>Fix:</b> ").append(esc(it).replace("\n", "<br>")).append("</div>") }
            }
            append("</td></tr>\n")
        }
        append("</tbody>\n</table>\n<p class=\"foot\">Generated by <code>./gradlew passkiCheck</code>. Catalog v")
        append(catalog.version).append(".</p>\n</main>\n</body>\n</html>\n")
    }

    private companion object {
        const val INDENT = "               "

        fun plural(n: Int, noun: String) = if (n == 1) "1 $noun" else "$n ${noun}s"

        fun esc(text: String): String = text
            .replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;").replace("\"", "&quot;")

        val CSS = """
            :root { --bg:#fff; --fg:#1b1f24; --muted:#5b636d; --line:#e3e6ea; --pass:#1a7f37; --warn:#9a6700; --fail:#cf222e; --skip:#6e7781; }
            @media (prefers-color-scheme: dark) { :root { --bg:#0d1117; --fg:#e6edf3; --muted:#9198a1; --line:#30363d; --pass:#3fb950; --warn:#d29922; --fail:#f85149; --skip:#8b949e; } }
            body { margin:0; background:var(--bg); color:var(--fg); font:15px/1.5 system-ui, -apple-system, sans-serif; }
            main { max-width:1100px; margin:0 auto; padding:24px 16px; }
            h1 { font-size:22px; margin:0 0 4px; } .summary, .foot { color:var(--muted); }
            table { width:100%; border-collapse:collapse; } th, td { text-align:left; padding:8px; border-bottom:1px solid var(--line); vertical-align:top; }
            a { color:inherit; } .fix { margin-top:6px; color:var(--muted); font-size:14px; }
            .badge { font:600 12px/1 ui-monospace, monospace; padding:3px 6px; border-radius:4px; border:1px solid currentColor; }
            .badge.pass { color:var(--pass); } .badge.warn { color:var(--warn); } .badge.fail { color:var(--fail); } .badge.skip { color:var(--skip); }
            @media (max-width:640px) { th:nth-child(3), td:nth-child(3) { display:none; } }
        """.trimIndent() + "\n"
    }
}
